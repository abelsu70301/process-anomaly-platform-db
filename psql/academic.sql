CREATE TABLE IF NOT EXISTS inheritance (
    pcid integer NOT NULL,
    ccid integer NOT NULL,
    rank smallint,
    mg smallint,
    CONSTRAINT pk_inheritance PRIMARY KEY (pcid, ccid),
    CONSTRAINT fk_inheritance_pcid FOREIGN KEY (pcid) REFERENCES class (cid),  /*inheritance.pcid 是一個 Foreign Key，參照 class.cid*/
    CONSTRAINT fk_inheritance_ccid FOREIGN KEY (ccid) REFERENCES class (cid)
);

CREATE TABLE IF NOT EXISTS object(
    oid integer NOT NULL,  /*oid 就是 Object ID，而且不能是 NULL*/
    title varchar(200),
    class varchar(50),
    des varchar(1000),
    address varchar(400),
    telephone varchar(50),
    sourceurl varchar(400),
    nclick integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_object PRIMARY KEY (oid)
);

