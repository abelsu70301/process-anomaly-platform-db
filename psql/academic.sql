CREATE TABLE IF NOT EXISTS co (
    cid integer NOT NULL,
    oid integer NOT NULL,
    rank smallint,
    mg smallint,
    CONSTRAINT pk_co PRIMARY KEY (cid, oid),  /*composite primary key*/
    CONSTRAINT fk_co_cid FOREIGN KEY (cid) REFERENCES class (cid),
    CONSTRAINT fk_co_oid FOREIGN KEY (oid) REFERENCES object (oid)
);

CREATE OR REPLACE FUNCTION insertClass(
    pcid integer,
    pname varchar,
    cname varchar
)

/*告訴 PostgreSQL：「這個 function 會回傳什麼、用什麼語言寫，以及裡面要準備哪些暫存變數*/
RETURNS integer  /*insertClass() 執行完之後，會回傳一個整數*/
LANGUAGE plpgsql
AS $$  /*從這裡開始，是 function 的程式內容*/
DECLARE  /*開始宣告 function 裡使用的暫存變數*/
    v_ccid integer;
    parent_idpath varchar(100);
BEGIN  /*function 真正要開始執行程式*/

/*如果 class 表裡找不到 cid = $1 的資料，就直接丟錯誤，不讓後面的新增繼續做*/
if exists (select 1 from class where cid = $1) = false then
    RAISE EXCEPTION 'Parent class with cid % does not exist', pcid;
end if;

/*檢查這個 cid 對應的名稱，是不是也真的等於 $2*/
if exists(
    select 1
    from class
    where cid = $1
        and name = $2
) = false then
    RAISE EXCEPTION 'Class with cid %, name % does not exist', $1, $2;
end if;

/*找這個 parent 底下，是不是已經有同名的 child class？*/
SELECT c.cid
INTO v_ccid /*把查到的結果存進變數*/
FROM inheritance AS i, class AS c
WHERE i.pcid = $1
    AND c.cid = i.ccid
    AND c.name = $3
ORDER BY c.cid /*如果剛好找到不只一筆符合的，就按 cid 排序*/
LIMIT 1; /*只取第一筆*/

/*果 v_ccid 還是 NULL，代表前面沒有找到符合條件的 child，所以現在才新增一筆新的 Class*/
IF v_ccid IS NULL THEN
    INSERT INTO class (name)
    VALUES ($3)
    RETURNING cid INTO v_ccid;  /*新增完成後，把這筆新資料產生出的 cid 取回來，存進 v_ccid*/
END IF;

INSERT INTO inheritance (pcid, ccid)  /*把 parent 的 cid 和 child 的 cid 寫進 inheritance*/
VALUES ($1, v_ccid)
ON CONFLICT ON CONSTRAINT pk_inheritance DO NOTHING;  /*如果違反 pk_inheritance 這個 Primary Key constraint，就不要新增，也不要報錯，直接略過*/

/*去 class 表找到目前 parent 的 idpath，再把它暫存在 parent_idpath 這個變數裡*/
SELECT idpath
INTO parent_idpath
FROM class
WHERE cid = $1;

/*更新「剛剛找到或新增的 child class」*/
UPDATE class
SET namepath = concat_ws('/', NULLIF($2, ''), $3),  /*用 / 把多個字串接起來;如果 $2 是空字串 ''，就把它當成 NULL*/
    idpath = concat_ws('/', NULLIF(parent_idpath, ''), v_ccid::varchar)
WHERE cid = v_ccid;  /*只更新 child 那一筆資料*/

/*把 child 的 cid 回傳，然後結束 function*/
RETURN v_ccid;
END;
$$;

CREATE OR REPLACE VIEW vd_subclass AS
SELECT p.cid AS pcid,
       p.name AS parent_name,
       c.cid AS cid,
       c.name AS child_name
FROM class p, inheritance i, class c
WHERE p.cid = i.pcid
  AND c.cid = i.ccid;

CREATE OR REPLACE VIEW vd_objectlist AS
SELECT c.cid AS cid,
       c.name AS class_name,
       o.oid AS oid,
       o.title AS object_title
FROM class c, co, object o
WHERE c.cid = co.cid
  AND co.oid = o.oid;

/*建立一個叫 vd_object 的 View*/
CREATE OR REPLACE VIEW vd_object AS
SELECT oid,
       title,
       class,
       des,
FROM object;  /*這個 View 的資料來源是 object table，並把這些欄位提供出來*/
