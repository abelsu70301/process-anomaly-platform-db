CREATE TABLE IF NOT EXISTS class ( /*如果 class 不存在才建立*/
    cid integer NOT NULL,  /*分類ID*/
    type smallint,  /*這個class的「類型代碼」*/
    name varchar(100),  /*分類名稱*/
    des varchar(1000),  /*des 是 description，存分類說明*/
    idpath varchar(100),  /*存這個分類在階層中的 ID 路徑*/
    namepath varchar(200),  /*存的是名稱路徑*/

    create_at timestamp without time zone,  /*建立這筆分類資料的時間*/
    update_at timestamp without time zone,  /*最後一次修改這筆資料的時間*/
    nobject integer,  /*number of object這個分類底下有多少個 Object 的計數欄位*/
    crank smallint,  /*class rank 類別(Class)的排序順序*/
    orank smallint,  /*object rank 物件(Object)在同一個類別中的排序順序*/

    code varchar(255),  /*代碼類欄位*/
    keywords varchar(255),  /*關鍵字*/
    nlevel smallint,  /*層級數值*/
    imgid smallint,  /*圖片相關 ID*/
    nclicktrue integer NOT NULL DEFAULT 0,  /*一個點擊／統計類欄位，預設 0*/
    nclick integer NOT NULL DEFAULT 0,  /*另一個點擊／統計類欄位，預設 0*/
    property smallint NOT NULL DEFAULT 0,  /*屬性／旗標類數值，預設 0*/

    CONSTRAINT pk_class PRIMARY KEY(cid),  /*CONSTRAINT:我要幫這張表定義一個限制規則*/
    CONSTRAINT uq_idpath UNIQUE (idpath),  /*idpath 每一筆都不能和別筆一樣*/
    CONSTRAINT uq_namepath UNIQUE (namepath)
);

