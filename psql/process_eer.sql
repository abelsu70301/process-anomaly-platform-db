\encoding UTF8

CREATE SCHEMA IF NOT EXISTS process_eer;

SET search_path TO process_eer, public;


-- ===== Object：EER 共用父類 =====

CREATE TABLE IF NOT EXISTS object (
    oid bigint GENERATED BY DEFAULT AS IDENTITY,
    object_type varchar(50) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_object PRIMARY KEY (oid)
);


-- ===== Dataset：Object 子類 =====

CREATE TABLE IF NOT EXISTS dataset (
    oid bigint NOT NULL,
    dataset_name varchar(100) NOT NULL,
    source varchar(100),
    version varchar(50),
    description text,
    CONSTRAINT pk_dataset PRIMARY KEY (oid),
    CONSTRAINT fk_dataset_object
        FOREIGN KEY (oid)
        REFERENCES object (oid)
);


-- ===== Model：Object 子類 =====

CREATE TABLE IF NOT EXISTS model (
    oid bigint NOT NULL,
    model_name varchar(100) NOT NULL,
    algorithm varchar(100) NOT NULL,
    version varchar(50),
    description text,
    CONSTRAINT pk_model PRIMARY KEY (oid),
    CONSTRAINT fk_model_object
        FOREIGN KEY (oid)
        REFERENCES object (oid)
);


-- ===== AnalysisRun：Object 子類，連結 Dataset 與 Model =====

CREATE TABLE IF NOT EXISTS analysis_run (
    oid bigint NOT NULL,
    dataset_oid bigint NOT NULL,
    model_oid bigint NOT NULL,
    threshold numeric(5,4),
    run_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status varchar(50),
    CONSTRAINT pk_analysis_run PRIMARY KEY (oid),
    CONSTRAINT fk_analysis_run_object
        FOREIGN KEY (oid)
        REFERENCES object (oid),
    CONSTRAINT fk_analysis_run_dataset
        FOREIGN KEY (dataset_oid)
        REFERENCES dataset (oid),
    CONSTRAINT fk_analysis_run_model
        FOREIGN KEY (model_oid)
        REFERENCES model (oid)
);